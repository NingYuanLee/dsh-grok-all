import { transform } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const result = await transform(await readFile(new URL('../src/client.js', import.meta.url), 'utf8'), { format: 'cjs', target: 'es2022', platform: 'browser' });
const built = `// Generated by npm run build. Do not edit.\nwindow.__ModuleLoader__.load({id: "dsh-grok-byapi", factory: (require) => {\nconst module = {exports: {}}; const exports = module.exports;\n${result.code}\nreturn module.exports;\n}});\n`;
await mkdir(new URL('../lib/', import.meta.url), { recursive: true });
await writeFile(new URL('../lib/client.js', import.meta.url), built);
